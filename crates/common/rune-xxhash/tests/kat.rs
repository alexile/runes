//! Official xxHash sanity-test vectors for XXH32 and XXH64.
//!
//! From `tests/sanity_test_vectors.h` in the reference repository
//! <https://github.com/Cyan4973/xxHash>, which `xxhsum --sanity-check`
//! (`cli/xsum_sanity_check.c`) verifies. Each input is a prefix of the
//! generated sanity buffer, hashed with seed `0` or `PRIME32`. A subset of the
//! table is kept: every length up to 100 (all tail and stripe paths) and a
//! spread of longer lengths.

#![allow(
    clippy::unreadable_literal,
    reason = "hex digests are kept as printed in the reference table"
)]

use rune_xxhash::{xxh32, xxh64};

/// `XSUM_fillTestBuffer`: a multiplicative byte generator.
fn sanity_buffer(len: usize) -> Vec<u8> {
    const PRIME32: u64 = 2_654_435_761;
    const PRIME64: u64 = 11_400_714_785_074_694_797;
    let mut byte_gen = PRIME32;
    (0..len)
        .map(|_| {
            let byte = byte_gen.to_be_bytes()[0];
            byte_gen = byte_gen.wrapping_mul(PRIME64);
            byte
        })
        .collect()
}

