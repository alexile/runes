//! `#[tool]`: a function becomes a unit struct implementing `Tool`.

use proc_macro2::{Span, TokenStream};
use quote::{quote, quote_spanned};
use syn::ext::IdentExt;
use syn::spanned::Spanned;
use syn::visit::Visit;
use syn::{
    Attribute, Expr, ExprLit, FnArg, Ident, Item, ItemFn, Lit, LitStr, Meta, Pat, ReturnType, Type,
    parse_quote,
};

use crate::paths;

/// Longest tool name, same as `rune_chain_core::MAX_TOOL_NAME_LEN`.
const MAX_NAME_LEN: usize = 64;

#[derive(Default)]
struct Options {
    name: Option<LitStr>,
    description: Option<LitStr>,
    krate: Option<syn::Path>,
}

impl Options {
    fn parse(attr: TokenStream) -> syn::Result<Self> {
        let mut opts = Self::default();
        let parser = syn::meta::parser(|meta| {
            if meta.path.is_ident("name") {
                opts.name = Some(meta.value()?.parse()?);
            } else if meta.path.is_ident("description") || meta.path.is_ident("desc") {
                opts.description = Some(meta.value()?.parse()?);
            } else if meta.path.is_ident("crate") {
                let lit: LitStr = meta.value()?.parse()?;
                opts.krate = Some(lit.parse()?);
            } else {
                return Err(
                    meta.error("unknown #[tool] option; expected `name`, `description` or `crate`")
                );
            }
            Ok(())
        });
        syn::parse::Parser::parse2(parser, attr)?;
        Ok(opts)
    }
}

/// One function argument, as a field of the generated argument struct.
struct Arg {
    ident: Ident,
    ty: Type,
    /// The function takes `&T`: pass `&args.field`.
    by_ref: bool,
    doc: Option<String>,
    default: bool,
}

pub fn expand(attr: TokenStream, item: TokenStream) -> syn::Result<TokenStream> {
    let opts = Options::parse(attr)?;
    let mut func = match syn::parse2::<Item>(item)? {
        Item::Fn(f) => f,
        other => {
            return Err(syn::Error::new(
                other.span(),
                "#[tool] goes on a free function (`fn` or `async fn`)",
            ));
        }
    };
    check_signature(&func)?;
    let args = take_args(&mut func)?;

    let fn_ident = func.sig.ident.clone();
    let fn_name = fn_ident.unraw().to_string();
    let (name, name_span) = opts.name.as_ref().map_or_else(
        || (fn_name.clone(), fn_ident.span()),
        |lit| (lit.value(), lit.span()),
    );
    check_name(&name, name_span)?;
    let description = opts
        .description
        .as_ref()
        .map(LitStr::value)
        .map(|d| d.trim().to_owned())
        .or_else(|| doc_text(&func.attrs))
        .filter(|d| !d.is_empty())
        .ok_or_else(|| {
            syn::Error::new(
                fn_ident.span(),
                "#[tool] needs a description: add a `///` doc comment or \
                 #[tool(description = \"...\")]",
            )
        })?;

    let core = paths::core(opts.krate.as_ref());
    let private = quote!(#core::__private);
    let serde_path = format!("{private}::serde");
    let schemars_path = format!("{private}::schemars");
    let struct_ident = Ident::new(&pascal_case(&fn_name), fn_ident.span());
    let vis = &func.vis;

    let fields = args.iter().map(|a| {
        let ident = &a.ident;
        let ty = &a.ty;
        let doc = a.doc.iter();
        let default = a.default.then(|| quote!(#[serde(default)]));
        quote! {
            #(#[doc = #doc])*
            #default
            #ident: #ty,
        }
    });
    let call_args = args.iter().map(|a| {
        let ident = &a.ident;
        if a.by_ref {
            quote!(&__args.#ident)
        } else {
            quote!(__args.#ident)
        }
    });
    let await_call = func.sig.asyncness.map(|_| quote!(.await));
    let output_span = match &func.sig.output {
        ReturnType::Default => fn_ident.span(),
        ReturnType::Type(_, ty) => ty.span(),
    };
    let convert = if returns_result(&func.sig.output) {
        quote_spanned! {output_span=>
            match __out {
                ::core::result::Result::Ok(__value) => #private::to_output(&__value),
                ::core::result::Result::Err(__err) => {
                    #[allow(unused_imports)]
                    use #private::{ViaDisplay as _, ViaToolError as _};
                    ::core::result::Result::Err((&#private::ErrWrap(__err)).to_tool_error())
                }
            }
        }
    } else {
        quote_spanned! {output_span=> #private::to_output(&__out) }
    };
    let struct_doc = format!("LLM tool `{name}`, generated by `#[tool]` from [`{fn_name}`].");

    Ok(quote! {
        #func

        #[doc = #struct_doc]
        #[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Hash)]
        #vis struct #struct_ident;

        #[allow(
            missing_docs,
            non_camel_case_types,
            clippy::all,
            clippy::pedantic,
            clippy::nursery
        )]
        const _: () = {
            #core::__rune_chain_core_require_macros!();

            #[derive(#private::serde::Deserialize, #private::schemars::JsonSchema)]
            #[serde(crate = #serde_path, deny_unknown_fields)]
            #[schemars(crate = #schemars_path)]
            struct __RuneToolArgs {
                #(#fields)*
            }

            #[#private::async_trait]
            #[automatically_derived]
            impl #core::Tool for #struct_ident {
                fn name(&self) -> &str {
                    #name
                }

                fn description(&self) -> &str {
                    #description
                }

                fn schema(&self) -> #private::serde_json::Value {
                    static SCHEMA: ::std::sync::OnceLock<#private::serde_json::Value> =
                        ::std::sync::OnceLock::new();
                    SCHEMA
                        .get_or_init(#private::tool_schema::<__RuneToolArgs>)
                        .clone()
                }

                async fn run(
                    &self,
                    input: &str,
                ) -> ::core::result::Result<::std::string::String, #core::ToolError> {
                    let __args: __RuneToolArgs = #private::parse_tool_args(#name, input)?;
                    let __out = #fn_ident(#(#call_args),*) #await_call;
                    #convert
                }
            }
        };
    })
}

fn check_signature(func: &ItemFn) -> syn::Result<()> {
    let sig = &func.sig;
    if !sig.generics.params.is_empty() || sig.generics.where_clause.is_some() {
        return Err(syn::Error::new(
            sig.generics.span(),
            "#[tool] functions can't be generic: the argument types make the JSON Schema",
        ));
    }
    if let Some(unsafety) = sig.unsafety {
        return Err(syn::Error::new(
            unsafety.span,
            "#[tool] functions can't be `unsafe`",
        ));
    }
    if let Some(variadic) = &sig.variadic {
        return Err(syn::Error::new(
            variadic.span(),
            "#[tool] functions can't be variadic",
        ));
    }
    Ok(())
}

/// Validate every argument, strip the `///` and `#[arg]` attributes the
/// compiler would reject, and return the argument list.
fn take_args(func: &mut ItemFn) -> syn::Result<Vec<Arg>> {
    let mut args = Vec::with_capacity(func.sig.inputs.len());
    for input in &mut func.sig.inputs {
        let pat_type = match input {
            FnArg::Receiver(r) => {
                return Err(syn::Error::new(
                    r.span(),
                    "#[tool] on methods isn't supported: write a free function and call \
                     the method from it",
                ));
            }
            FnArg::Typed(t) => t,
        };
        let ident = match &*pat_type.pat {
            Pat::Ident(p) if p.by_ref.is_none() && p.subpat.is_none() => p.ident.clone(),
            other => {
                return Err(syn::Error::new(
                    other.span(),
                    "unsupported argument pattern in #[tool]: use a plain name, like \
                     `city: String`",
                ));
            }
        };
        let (ty, by_ref) = owned_type(&pat_type.ty)?;
        let mut doc = doc_text(&pat_type.attrs);
        let mut default = false;
        for attr in &pat_type.attrs {
            if !attr.path().is_ident("arg") {
                continue;
            }
            attr.parse_nested_meta(|meta| {
                if meta.path.is_ident("desc") || meta.path.is_ident("description") {
                    let lit: LitStr = meta.value()?.parse()?;
                    doc = Some(lit.value().trim().to_owned()).filter(|d| !d.is_empty());
                } else if meta.path.is_ident("default") {
                    default = true;
                } else {
                    return Err(meta.error("unknown #[arg] option; expected `desc` or `default`"));
                }
                Ok(())
            })?;
        }
        pat_type
            .attrs
            .retain(|a| !a.path().is_ident("doc") && !a.path().is_ident("arg"));
        args.push(Arg {
            ident,
            ty,
            by_ref,
            doc,
            default,
        });
    }
    Ok(args)
}

/// The owned type the argument is deserialized into, and whether the
/// function borrows it.
fn owned_type(ty: &Type) -> syn::Result<(Type, bool)> {
    match ty {
        Type::Paren(p) => owned_type(&p.elem),
        Type::Group(g) => owned_type(&g.elem),
        Type::Reference(r) => {
            if r.mutability.is_some() {
                return Err(syn::Error::new(
                    r.span(),
                    "#[tool] arguments can't be `&mut`: the value comes from the model",
                ));
            }
            let owned: Type = match &*r.elem {
                Type::Path(p) if p.qself.is_none() && p.path.is_ident("str") => {
                    parse_quote!(::std::string::String)
                }
                Type::Slice(s) => {
                    let elem = &s.elem;
                    parse_quote!(::std::vec::Vec<#elem>)
                }
                other => other.clone(),
            };
            check_owned(&owned)?;
            Ok((owned, true))
        }
        other => {
            check_owned(other)?;
            Ok((other.clone(), false))
        }
    }
}

/// Reject borrowed, `impl Trait` and inferred types inside an argument type.
fn check_owned(ty: &Type) -> syn::Result<()> {
    struct Check(Option<syn::Error>);
    impl Visit<'_> for Check {
        fn visit_type(&mut self, ty: &Type) {
            if self.0.is_some() {
                return;
            }
            let msg = match ty {
                Type::Reference(_) => Some(
                    "#[tool] arguments can borrow only at the top level (`&str`, `&[T]`, `&T`); \
                     use an owned type here",
                ),
                Type::ImplTrait(_) => Some("#[tool] arguments can't use `impl Trait`"),
                Type::Infer(_) => Some("#[tool] arguments need a concrete type"),
                Type::Never(_) => Some("#[tool] arguments can't be `!`"),
                _ => None,
            };
            if let Some(msg) = msg {
                self.0 = Some(syn::Error::new(ty.span(), msg));
                return;
            }
            syn::visit::visit_type(self, ty);
        }

        fn visit_lifetime(&mut self, lt: &syn::Lifetime) {
            if self.0.is_none() && lt.ident != "static" {
                self.0 = Some(syn::Error::new(
                    lt.span(),
                    "#[tool] arguments can't hold borrowed data; use an owned type",
                ));
            }
        }
    }
    let mut check = Check(None);
    check.visit_type(ty);
    check.0.map_or(Ok(()), Err)
}

/// `true` for `Result<..>` (any path ending in `Result`, such as
/// `io::Result<T>` or `anyhow::Result<T>`).
fn returns_result(output: &ReturnType) -> bool {
    fn is_result(ty: &Type) -> bool {
        match ty {
            Type::Paren(p) => is_result(&p.elem),
            Type::Group(g) => is_result(&g.elem),
            Type::Path(p) => p
                .path
                .segments
                .last()
                .is_some_and(|s| s.ident == "Result" && !s.arguments.is_none()),
            _ => false,
        }
    }
    matches!(output, ReturnType::Type(_, ty) if is_result(ty))
}

fn check_name(name: &str, span: Span) -> syn::Result<()> {
    let ok = !name.is_empty()
        && name.len() <= MAX_NAME_LEN
        && name
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'_' || b == b'-');
    if ok {
        Ok(())
    } else {
        Err(syn::Error::new(
            span,
            format!(
                "tool name `{name}` must be 1 to {MAX_NAME_LEN} characters of \
                 A-Z, a-z, 0-9, `_` and `-`"
            ),
        ))
    }
}

/// The text of the `///` comments in `attrs`, one leading space per line
/// removed, or `None` if there is none.
pub fn doc_text(attrs: &[Attribute]) -> Option<String> {
    let mut lines: Vec<String> = Vec::new();
    for attr in attrs {
        if !attr.path().is_ident("doc") {
            continue;
        }
        if let Meta::NameValue(nv) = &attr.meta
            && let Expr::Lit(ExprLit {
                lit: Lit::Str(s), ..
            }) = &nv.value
        {
            for line in s.value().split('\n') {
                lines.push(line.strip_prefix(' ').unwrap_or(line).trim_end().to_owned());
            }
        }
    }
    let text = lines.join("\n");
    let text = text.trim();
    (!text.is_empty()).then(|| text.to_owned())
}

/// `get_weather` -> `GetWeather`.
fn pascal_case(snake: &str) -> String {
    let mut out = String::with_capacity(snake.len());
    for part in snake.split('_').filter(|p| !p.is_empty()) {
        let mut chars = part.chars();
        if let Some(first) = chars.next() {
            out.extend(first.to_uppercase());
            out.push_str(chars.as_str());
        }
    }
    if !out.starts_with(|c: char| c.is_alphabetic()) {
        out.insert_str(0, "Tool");
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn pascal() {
        assert_eq!(pascal_case("get_weather"), "GetWeather");
        assert_eq!(pascal_case("add"), "Add");
        assert_eq!(pascal_case("__x_y__"), "XY");
        assert_eq!(pascal_case("_1"), "Tool1");
        assert_eq!(pascal_case("élan_vital"), "ÉlanVital");
    }

    #[test]
    fn names() {
        assert!(check_name("get_weather-2", Span::call_site()).is_ok());
        assert!(check_name("", Span::call_site()).is_err());
        assert!(check_name("has space", Span::call_site()).is_err());
        assert!(check_name(&"a".repeat(65), Span::call_site()).is_err());
    }
}
