//! Postgres + [pgvector] backend for `rune-vectorstore`.
//!
//! [`PgVectorStore`] implements the async
//! [`VectorStore`](rune_vectorstore::VectorStore) trait on a Postgres table
//! with a `vector(n)` column:
//!
//! - **Indexes**: HNSW or `IVFFlat` ([`PgIndex`]), built with the operator
//!   class matching the [`Metric`](rune_vectorstore::Metric), or none for
//!   exact scans. `ef_search`, `probes` and iterative scans are set per
//!   query inside a transaction.
//! - **Safe SQL**: schema, table and index names must be plain identifiers
//!   and are quoted; every id, vector, text, metadata key and value, limit
//!   and setting is a bound parameter. [`Filter`](rune_vectorstore::Filter)s
//!   compile to `jsonb` conditions with the in-memory store's semantics.
//! - **Batched upserts**: one transaction, `INSERT ... ON CONFLICT DO
//!   UPDATE` over array parameters, `upsert_batch_rows` rows per statement.
//! - **Validated input**: NaN or infinite components, empty vectors, zero
//!   vectors under cosine, dimension mismatches, empty or duplicate ids and
//!   NUL characters (which Postgres text cannot hold) are rejected before
//!   any I/O.
//! - **Quiet errors**: messages carry Postgres error codes and text, never
//!   the connection string or password; `Debug` shows no credentials.
//!
//! The SQL is generated by pure functions, unit tested without a
//! database. Integration tests run against a real server when
//! `DATABASE_URL` is set.
//!
//! [pgvector]: https://github.com/pgvector/pgvector
//!
//! # Example
//!
//! ```no_run
//! use rune_vectorstore::{Metric, Query, Record, VectorStore};
//! use rune_vectorstore_pgvector::{PgIndex, PgVectorConfig, PgVectorStore};
//!
//! # async fn demo() -> Result<(), rune_vectorstore::StoreError> {
//! let config = PgVectorConfig::new("chunks", 384)
//!     .with_metric(Metric::Cosine)
//!     .with_index(PgIndex::Hnsw { m: 16, ef_construction: 64 });
//! let store = PgVectorStore::connect("postgres://app@localhost/rag", config).await?;
//! store.upsert(vec![Record::new("c1", vec![0.1; 384]).with_content("...")]).await?;
//! let hits = store.query(&Query::new(vec![0.1; 384], 10)).await?;
//! # Ok(())
//! # }
//! ```

