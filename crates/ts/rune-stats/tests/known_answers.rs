const fn method(exact: bool) -> Method {
    if exact {
        Method::Exact
    } else {
        Method::Asymptotic
    }
}

#[test]
fn mann_whitney() {
    for (case, &(x, y, alternative, continuity, exact, u, p)) in MANN_WHITNEY.iter().enumerate() {
        let options = MannWhitneyOptions::default()
            .with_alternative(alternative)
            .with_continuity(continuity)
            .with_method(method(exact));
        let result = mann_whitney_u(x, y, &options).unwrap();
        assert_eq!(result.u, u, "case {case}");
        assert_eq!(result.exact, exact);
        assert_close(
            result.p_value,
            p,
            1e-12,
            &format!("mann-whitney case {case}"),
        );
    }
}

#[test]
fn kolmogorov_smirnov() {
    for (case, &(x, y, alternative, exact, d, p)) in KS.iter().enumerate() {
        let options = KsOptions::default()
            .with_alternative(alternative)
            .with_method(method(exact));
        let result = ks_two_sample(x, y, &options).unwrap();
        assert_close(result.statistic, d, 1e-15, &format!("ks D case {case}"));
        assert_close(result.p_value, p, 1e-10, &format!("ks p case {case}"));
    }
}

#[test]
fn wilcoxon() {
    for (case, &(diffs, alternative, zero_method, continuity, exact, w_plus, p)) in
        WILCOXON.iter().enumerate()
    {
        let options = WilcoxonOptions::default()
            .with_alternative(alternative)
            .with_zero_method(zero_method)
            .with_continuity(continuity)
            .with_method(method(exact));
        let result = wilcoxon_signed_rank(diffs, &options).unwrap();
        assert_eq!(result.w_plus, w_plus, "case {case}");
        assert_close(result.p_value, p, 1e-12, &format!("wilcoxon case {case}"));
    }
}

#[test]
fn r_documentation_examples() {
    // ?wilcox.test, Hollander & Wolfe (1973) p. 69: W = 35, p = 0.1272.
    let x = [0.80, 0.83, 1.89, 1.04, 1.45, 1.38, 1.91, 1.64, 0.73, 1.46];
    let y = [1.15, 0.88, 0.90, 0.74, 1.21];
    let options = MannWhitneyOptions::default().with_alternative(Alternative::Greater);
    let result = mann_whitney_u(&x, &y, &options).unwrap();
    assert_eq!(result.u, 35.0);
    assert!(result.exact);
    assert_close(result.p_value, 0.127_206_127_206_127_2, 1e-14, "R W");

    // ?wilcox.test, Hollander & Wolfe (1973) p. 29: V = 40, p = 0.03906.
    let x = [1.83, 0.50, 1.62, 2.48, 1.68, 1.88, 1.55, 3.06, 1.30];
    let y = [0.878, 0.647, 0.598, 2.05, 1.06, 1.29, 1.06, 3.14, 1.29];
    let result = wilcoxon_paired(&x, &y, &WilcoxonOptions::default()).unwrap();
    assert_eq!(result.w_plus, 40.0);
    assert!(result.exact);
    assert_close(result.p_value, 0.039_062_5, 1e-14, "R V");
}

#[test]
fn median_confidence_intervals() {
    for &(n, confidence, k, achieved) in MEDIAN_CI {
        let data: Vec<f64> = (0..n).map(|i| i as f64).collect();
        let ci = median_ci(&data, confidence).unwrap();
        assert_eq!(ci.lower, (k - 1) as f64, "n={n} conf={confidence}");
        assert_eq!(ci.upper, (n - k) as f64, "n={n} conf={confidence}");
        assert_close(
            ci.achieved_confidence,
            achieved,
            1e-12,
            "median ci coverage",
        );
    }
}

#[test]
fn hodges_lehmann() {
    for &(x, y, confidence, estimate, lower, upper, achieved) in HL_SHIFT {
        let ci = hodges_lehmann_shift(x, y, confidence).unwrap();
        assert!(ci.exact);
        assert_close(ci.estimate, estimate, 1e-14, "shift estimate");
        assert_eq!((ci.lower, ci.upper), (lower, upper));
        assert_close(ci.achieved_confidence, achieved, 1e-14, "shift coverage");
    }
    for &(diffs, confidence, estimate, lower, upper, achieved) in HL_ONE {
        let ci = hodges_lehmann_one_sample(diffs, confidence).unwrap();
        assert!(ci.exact);
        assert_close(ci.estimate, estimate, 1e-14, "pseudo-median");
        assert_eq!((ci.lower, ci.upper), (lower, upper));
        assert_close(
            ci.achieved_confidence,
            achieved,
            1e-14,
            "one-sample coverage",
        );
    }
}

