#[test]
fn gamma_functions() {
    for &(x, expected) in LN_GAMMA {
        assert_close(ln_gamma(x), expected, 1e-13, &format!("ln_gamma({x})"));
    }
    assert!(ln_gamma(1.0).abs() < 1e-14 && ln_gamma(2.0).abs() < 1e-14);
    for &(a, x, p, q) in INCOMPLETE_GAMMA {
        // The prefactor e^{a ln x − x − ln Γ(a)} loses ~log10(a) digits.
        let rel = if a >= 500.0 { 1e-10 } else { 1e-12 };
        assert_close(gamma_p(a, x), p, rel, &format!("P({a}, {x})"));
        assert_close(gamma_q(a, x), q, rel, &format!("Q({a}, {x})"));
    }
    // scipy.stats.chi2.sf(3.841458820694124, 1)
    assert_close(
        chi_squared_sf(3.841458820694124, 1.0),
        0.05,
        1e-13,
        "chi2.sf",
    );
    assert_eq!(chi_squared_sf(0.0, 3.0), 1.0);
    assert_eq!(chi_squared_sf(-1.0, 3.0), 1.0);
    assert!(chi_squared_sf(1.0, 0.0).is_nan());
    assert_eq!(gamma_p(2.0, 0.0), 0.0);
    assert_eq!(gamma_q(2.0, 0.0), 1.0);
    assert_eq!(gamma_q(2.0, f64::INFINITY), 0.0);
    assert!(gamma_q(0.0, 1.0).is_nan());
    assert!(gamma_p(1.0, -1.0).is_nan());
    assert!(ln_gamma(0.0).is_nan());
}

