/// Relative closeness, with an absolute floor for values near zero.
#[track_caller]
fn assert_close(actual: f64, expected: f64, rel: f64, what: &str) {
    let tolerance = rel * expected.abs().max(f64::MIN_POSITIVE);
    assert!(
        (actual - expected).abs() <= tolerance,
        "{what}: got {actual:e}, expected {expected:e} (rel diff {:e})",
        (actual - expected).abs() / expected.abs()
    );
}

