//! Regenerates `src/data.rs` from local copies of the Unicode data files
//! pinned in `data/sources.toml`.
//!
//! This is not a test: it is ignored by default and never touches the
//! network. Download the three files into one directory, check their
//! checksums against `data/sources.toml`, then run
//!
//! ```text
//! RUNE_IDNA_UCD_DIR=<dir> cargo test -p rune-idna --test regenerate -- --ignored
//! ```

#![allow(
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::panic,
    reason = "a generator run by hand fails loudly by design"
)]

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// Parses a `XXXX` or `XXXX..YYYY` field into an inclusive range.
fn parse_range(field: &str) -> (u32, u32) {
    let field = field.trim();
    let parse = |s: &str| u32::from_str_radix(s.trim(), 16).expect("hex code point");
    let (lo, hi) = field.split_once("..").unwrap_or((field, field));
    (parse(lo), parse(hi))
}

/// The data columns of every non-comment line, split on `;`.
fn records(text: &str) -> impl Iterator<Item = Vec<&str>> {
    text.lines().filter_map(|line| {
        let data = line.split('#').next().unwrap_or("").trim();
        (!data.is_empty()).then(|| data.split(';').map(str::trim).collect())
    })
}

/// Sorts ranges and merges overlapping or adjacent ones.
fn merge(mut ranges: Vec<(u32, u32)>) -> Vec<(u32, u32)> {
    ranges.sort_unstable();
    let mut out: Vec<(u32, u32)> = Vec::new();
    for (lo, hi) in ranges {
        match out.last_mut() {
            Some(last) if lo <= last.1 + 1 => last.1 = last.1.max(hi),
            _ => out.push((lo, hi)),
        }
    }
    out
}

/// Ranges must not contain surrogates, or they cannot be `char` literals.
fn assert_no_surrogates(ranges: &[(u32, u32)]) {
    for &(lo, hi) in ranges {
        assert!(
            hi < 0xD800 || lo > 0xDFFF,
            "range {lo:X}..{hi:X} spans surrogates"
        );
    }
}

fn version_of(text: &str) -> String {
    text.lines()
        .find_map(|l| l.strip_prefix("# Version: "))
        .expect("version line")
        .trim()
        .to_owned()
}

fn char_lit(cp: u32) -> String {
    format!("'\\u{{{cp:x}}}'")
}

fn write_ranges(out: &mut String, doc: &str, name: &str, ranges: &[(u32, u32)]) {
    writeln!(out, "{doc}").unwrap();
    writeln!(out, "#[rustfmt::skip]").unwrap();
    writeln!(out, "pub static {name}: &[(char, char)] = &[").unwrap();
    for &(lo, hi) in ranges {
        writeln!(out, "    ({}, {}),", char_lit(lo), char_lit(hi)).unwrap();
    }
    writeln!(out, "];\n").unwrap();
}

#[test]
#[ignore = "regenerates src/data.rs from local Unicode data files"]
fn regenerate() {
    let Some(dir) = std::env::var_os("RUNE_IDNA_UCD_DIR").map(PathBuf::from) else {
        eprintln!("set RUNE_IDNA_UCD_DIR to a directory with the Unicode data files");
        return;
    };
    let read = |name: &str| std::fs::read_to_string(dir.join(name)).expect(name);
    let confusables = read("confusables.txt");
    let identifier = read("IdentifierStatus.txt");
    let mapping = read("IdnaMappingTable.txt");

    let version = version_of(&confusables);
    assert_eq!(
        version,
        version_of(&identifier),
        "IdentifierStatus.txt version"
    );
    assert_eq!(
        version,
        version_of(&mapping),
        "IdnaMappingTable.txt version"
    );

    // confusables.txt: `source ; target sequence ; MA`.
    let mut pairs: Vec<(u32, Vec<u32>)> = records(&confusables)
        .map(|cols| {
            let (lo, hi) = parse_range(cols[0]);
            assert_eq!(lo, hi, "confusable sources are single code points");
            let target = cols[1]
                .split_whitespace()
                .map(|s| u32::from_str_radix(s, 16).expect("hex target"))
                .collect();
            (lo, target)
        })
        .collect();
    pairs.sort_unstable_by_key(|p| p.0);
    pairs.dedup_by_key(|p| p.0);

    // IdentifierStatus.txt: `range ; Allowed`.
    let allowed = merge(
        records(&identifier)
            .filter(|cols| cols.get(1) == Some(&"Allowed"))
            .map(|cols| parse_range(cols[0]))
            .collect(),
    );

    // IdnaMappingTable.txt: `range ; valid ; ; NV8|XV8` marks code points that
    // UTS #46 accepts but IDNA2008 (RFC 5892) does not.
    let excluded = merge(
        records(&mapping)
            .filter(|cols| matches!(cols.get(3), Some(&("NV8" | "XV8"))))
            .map(|cols| parse_range(cols[0]))
            .collect(),
    );
    assert_no_surrogates(&allowed);
    assert_no_surrogates(&excluded);

    let mut out = String::new();
    writeln!(
        out,
        "// @generated by tests/regenerate.rs from the Unicode Character Database,\n\
         // version {version}: security/confusables.txt, security/IdentifierStatus.txt\n\
         // and idna/IdnaMappingTable.txt. Unicode License v3; see NOTICE.\n\
         // Do not edit: see data/sources.toml.\n\
         \n\
         //! Embedded Unicode data: {} confusable prototypes, {} identifier-profile\n\
         //! ranges and {} IDNA2008-excluded ranges.\n",
        pairs.len(),
        allowed.len(),
        excluded.len()
    )
    .unwrap();
    writeln!(
        out,
        "/// Version of the Unicode data files this module was generated from.\n\
         pub const UNICODE_VERSION: &str = \"{version}\";\n"
    )
    .unwrap();

    writeln!(
        out,
        "/// UTS #39 confusable prototypes (`confusables.txt`), sorted by source.\n\
         #[rustfmt::skip]\n\
         pub static CONFUSABLES: &[(char, &str)] = &["
    )
    .unwrap();
    for (src, target) in &pairs {
        let mut t = String::new();
        for cp in target {
            match char::from_u32(*cp) {
                Some(c) if c.is_ascii_graphic() && c != '"' && c != '\\' => t.push(c),
                _ => write!(t, "\\u{{{cp:x}}}").unwrap(),
            }
        }
        writeln!(out, "    ({}, \"{t}\"),", char_lit(*src)).unwrap();
    }
    writeln!(out, "];\n").unwrap();

    write_ranges(
        &mut out,
        "/// Inclusive ranges with UTS #39 `Identifier_Status=Allowed`, sorted.",
        "IDENTIFIER_ALLOWED",
        &allowed,
    );
    write_ranges(
        &mut out,
        "/// Inclusive ranges that UTS #46 marks `NV8` or `XV8`: valid under UTS #46\n\
         /// but not PVALID under IDNA2008 (RFC 5892), sorted.",
        "IDNA2008_EXCLUDED",
        &excluded,
    );
    let out = out.trim_end().to_owned() + "\n";

    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("src/data.rs");
    std::fs::write(&path, out).expect("write src/data.rs");
    eprintln!("wrote {}", path.display());
}
