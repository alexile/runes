//! Platform-independent floating-point helpers.
//!
//! The scoring formulas are evaluated in IEEE 754 binary64 with the same
//! operations, in the same order, as the FIRST reference calculators
//! (JavaScript), so every intermediate value is bit-for-bit the same. Only
//! `+ - * /`, `floor`, `ceil` and `round` are used, which IEEE 754 defines
//! exactly. `f64::powf` is not: its accuracy depends on the platform's libm.
//! [`powi_correctly_rounded`] replaces it.

#![allow(
    clippy::suboptimal_flops,
    reason = "the formulas must round exactly as the reference calculators do; fusing into mul_add would change results"
)]

/// `x` raised to a small positive integer power, correctly rounded.
///
/// JavaScript's `Math.pow` (V8) returns the correctly rounded power for every
/// input the CVSS v3 formulas can produce (checked against exact rational
/// arithmetic for all 138 of them; see the tests). This computes the power
/// in double-double arithmetic (about 106 bits) and rounds once, so it gives
/// the same results on every platform without depending on libm.
pub fn powi_correctly_rounded(x: f64, n: u32) -> f64 {
    let mut result = (1.0, 0.0);
    let mut base = (x, 0.0);
    let mut exp = n;
    while exp > 0 {
        if exp & 1 == 1 {
            result = dd_mul(result, base);
        }
        exp >>= 1;
        if exp > 0 {
            base = dd_mul(base, base);
        }
    }
    result.0 + result.1
}

/// Splits `a` into two halves of 26 bits each (Veltkamp), exactly.
fn split(a: f64) -> (f64, f64) {
    let c = 134_217_729.0 * a; // 2^27 + 1
    let hi = c - (c - a);
    (hi, a - hi)
}

/// The exact product `a * b` as `p + e` (Dekker), without FMA.
fn two_prod(a: f64, b: f64) -> (f64, f64) {
    let p = a * b;
    let (ah, al) = split(a);
    let (bh, bl) = split(b);
    let e = ((ah * bh - p) + ah * bl + al * bh) + al * bl;
    (p, e)
}

/// `a + b` as `s + e` with `|e| <= ulp(s) / 2`, given `|a| >= |b|`.
fn fast_two_sum(a: f64, b: f64) -> (f64, f64) {
    let s = a + b;
    (s, b - (s - a))
}

/// Double-double product.
fn dd_mul(x: (f64, f64), y: (f64, f64)) -> (f64, f64) {
    let (p, e) = two_prod(x.0, y.0);
    let e = e + (x.0 * y.1 + x.1 * y.0);
    fast_two_sum(p, e)
}

/// JavaScript's `Math.round` for non-negative finite input: the nearest
/// integer, halves rounded up.
pub fn js_round(x: f64) -> f64 {
    let floor = x.floor();
    if x - floor >= 0.5 { floor + 1.0 } else { floor }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Every `(x, n)` the CVSS v3.0/v3.1 formulas raise to a power, with
    /// V8's `Math.pow(x, n)`, as IEEE 754 bit patterns. Generated by
    /// enumerating all ISS and MISS values in Node.js
    /// (`tests/oracle/pow.js`); each result was checked to be the correctly
    /// rounded exact power.
    const POW_CASES: &str = include_str!("../tests/data/pow.txt");

    fn bits(hex: &str) -> f64 {
        f64::from_bits(u64::from_str_radix(hex, 16).unwrap())
    }

    #[test]
    fn pow_matches_javascript_for_every_cvss_input() {
        let mut count = 0;
        for line in POW_CASES.lines() {
            let mut fields = line.split_whitespace();
            let x = bits(fields.next().unwrap());
            let n: u32 = fields.next().unwrap().parse().unwrap();
            let expected = bits(fields.next().unwrap());
            let got = powi_correctly_rounded(x, n);
            assert_eq!(
                got.to_bits(),
                expected.to_bits(),
                "{x}^{n}: {got} != {expected}"
            );
            count += 1;
        }
        assert_eq!(count, 138);
    }

    #[test]
    fn pow_small_cases() {
        assert_eq!(powi_correctly_rounded(2.0, 10), 1024.0);
        assert_eq!(powi_correctly_rounded(-0.5, 3), -0.125);
        assert_eq!(powi_correctly_rounded(0.0, 15), 0.0);
        assert_eq!(powi_correctly_rounded(1.5, 1), 1.5);
    }

    #[test]
    fn js_round_halves_go_up() {
        assert_eq!(js_round(0.5), 1.0);
        assert_eq!(js_round(2.5), 3.0);
        assert_eq!(js_round(2.4999), 2.0);
        assert_eq!(js_round(0.499_999_999_999_999_94), 0.0);
        assert_eq!(js_round(0.0), 0.0);
    }
}
